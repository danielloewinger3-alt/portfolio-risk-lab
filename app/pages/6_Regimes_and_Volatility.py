"""Page 6: Regimes and volatility forecast (ML on risk, never on returns)."""

from __future__ import annotations

import streamlit as st

import _bootstrap  # noqa: F401
from components import data as cached
from components.kpi import Tile, kpi_row
from components.layout import chart, disclaimer_footer, guarded, how_calculated
from components.page import start_page
from risklab.formatting import fmt_date, fmt_pct, fmt_ratio
from risklab.ml.evaluation import MODEL_NAMES, model_name
from risklab.ml.volatility import MIN_OBS as VOL_MIN_OBS
from risklab.ml.volatility import vol_takeaway
from risklab.risk.metrics import wealth_index
from risklab.viz import charts, tables, text

p, offline, d = start_page(
    "Regimes and volatility",
    "What market environment are we in, how does this portfolio behave in each, and which "
    "model best forecasts its volatility over the next month?",
)

tab_regimes, tab_vol = st.tabs(["Market regimes", "Volatility forecast bake-off"])

# ---------------------------------------------------------------- regimes
with tab_regimes:
    with st.spinner("Fitting a 3-state hidden Markov model on the benchmark..."):
        ra = guarded("market regimes", lambda: cached.regimes(p, offline))
    if ra is not None:
        st.info(ra.takeaway, icon=":material/insights:")
        kpi_row(
            [
                Tile("Current regime", ra.current_regime, f"filtered, as of {fmt_date(ra.as_of)}"),
                Tile(
                    f"P({ra.current_regime})",
                    fmt_pct(ra.current_probs[ra.current_regime], 1),
                    "uses data up to that date only",
                ),
                Tile(
                    "Stress vol / Calm vol",
                    f"{fmt_ratio(ra.stress_vol_multiple, 1)}x",
                    "portfolio, in-sample",
                ),
            ]
        )
        chart(charts.regime_chart(wealth_index(d.benchmark_returns), ra.labels, p.benchmark))
        st.caption(
            "Shading uses Viterbi (smoothed) labels fitted on the whole window: in-sample "
            "and descriptive, because it uses future data. The current regime above comes "
            "from filtered probabilities, which use no future data."
        )
        c1, c2 = st.columns(2)
        with c1:
            chart(charts.regime_probability_bar(ra.current_probs, ra.as_of))
            st.caption(text.regime_probs_sentence(ra.current_probs))
        with c2:
            chart(charts.transition_heatmap(ra.model.transition_table()))
        st.subheader("This portfolio in each regime (in-sample, descriptive)")
        st.dataframe(
            tables.regime_table(ra.summary, ra.model.expected_durations()), hide_index=True
        )
        st.caption(
            "Annualized return is the arithmetic mean · 252, because regime days are not "
            "contiguous; a regime with few days can show an extreme figure. Expected "
            "duration = 1 / (1 - probability of staying)."
        )
        if not ra.model.converged:
            st.warning("The HMM's best restart did not fully converge; treat regimes with care.")

# ---------------------------------------------------------------- volatility bake-off
with tab_vol:
    committed = cached.committed_vol_result(p, d)
    st.markdown(
        "Four models forecast annualized volatility over the next 21 trading days, "
        "evaluated walk-forward (expanding window, purged labels, refit every 21 days). "
        "Lower QLIKE is better; it penalizes under-forecasting risk."
    )
    if committed is not None:
        meta = (cached.eval_json("volatility_results.json") or {}).get("meta", {})
        st.success(committed["takeaway"], icon=":material/emoji_events:")
        st.caption(
            "Committed result for this portfolio and window: docs/eval/volatility_results.json, "
            f"generated by scripts/run_walkforward.py on data through "
            f"{meta.get('data_snapshot_date', 'n/a')} "
            f"({committed['evaluation']['n_points']} evaluation points, "
            f"{committed['evaluation']['first_origin']} to "
            f"{committed['evaluation']['last_origin']})."
        )
        st.dataframe(
            tables.vol_metrics_table(committed["metrics"], committed["winner"]), hide_index=True
        )
        st.dataframe(tables.current_forecast_table(committed["current_forecast"]), hide_index=True)

    n_obs = len(d.portfolio_returns)
    if n_obs < VOL_MIN_OBS:
        st.warning(
            f"The bake-off needs at least {VOL_MIN_OBS:,} daily returns (5 years); this window "
            f"has {n_obs:,}. Lengthen the window on Home.",
            icon=":material/history:",
        )
    else:
        run_key = f"wf_ok_{hash(p)}_{offline}"
        if not st.session_state.get(run_key, False):
            label = (
                "Show the forecast vs realized chart (runs the walk-forward, about 5 s)"
                if committed is not None
                else "Run the walk-forward bake-off for this portfolio (about 5 s)"
            )
            if st.button(label, key="w_wf_run", icon=":material/play_arrow:"):
                st.session_state[run_key] = True
                st.rerun()
        if st.session_state.get(run_key, False):
            with st.spinner("Running the walk-forward evaluation..."):
                ev = guarded("the volatility bake-off", lambda: cached.walk_forward(p, offline))
            if ev is not None:
                if committed is None:
                    st.success(vol_takeaway(ev), icon=":material/emoji_events:")
                    st.dataframe(
                        tables.vol_metrics_table(tables.vol_rows_from_frame(ev.metrics), ev.winner),
                        hide_index=True,
                    )
                    st.dataframe(
                        tables.current_forecast_table(ev.current_forecast), hide_index=True
                    )
                chart(charts.forecast_vs_realized_chart(ev.forecasts, ev.realized, MODEL_NAMES))
                purge = ev.max_purge_violation()
                st.caption(
                    f"Winner: {model_name(ev.winner)}. Leakage guard: "
                    + (
                        "no training label or fit extends past its forecast date."
                        if purge <= 0
                        else f"VIOLATION, data up to {purge} days after a forecast date."
                    )
                    + (
                        f" Dropped features: {', '.join(ev.dropped_features)}."
                        if ev.dropped_features
                        else ""
                    )
                )

    caveats = (cached.eval_json("volatility_results.json") or {}).get("caveats", [])
    if caveats:
        with st.expander("Caveats of this evaluation", icon=":material/rule:"):
            for c in caveats:
                st.markdown(f"- {c}")

how_calculated(
    "Regimes: a 3-state Gaussian HMM on the benchmark's daily returns (10 seeded restarts), "
    "states sorted by variance as Calm, Transition, Stress. Current probabilities come from "
    "a hand-written forward filter that only uses data up to each date. Volatility: rolling "
    "21-day, EWMA (λ = 0.94), GARCH(1,1) with Student-t errors, and LightGBM on log "
    "realized volatility, compared on QLIKE, RMSE, and MAE with Newey-West standard errors.",
    "ML specification (regimes and volatility)",
)
disclaimer_footer()
