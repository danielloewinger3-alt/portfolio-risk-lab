"""Run sample Q&A questions through retrieval, the LLM, and the answer verifier.

For each (question, holdings) pair below, retrieves 6 passages from the committed index
(hybrid, per-ticker quota 2), calls :func:`risklab.rag.answer.answer` with the configured
provider (temperature 0, seed 42), and records: first-pass verification, retries, claims
kept and dropped (with reasons), citation validity, and the answer text for spot checks.

Writes ``docs/eval/qa_verification.json`` and ``docs/eval/qa_verification.md``.

Usage::

    uv run python scripts/eval_qa.py [--provider ollama]
"""

from __future__ import annotations

import argparse
import json
import logging
import subprocess
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from risklab.config import get_settings, load_settings
from risklab.llm.client import make_client, resolve_provider
from risklab.portfolio import SAMPLE_PORTFOLIOS
from risklab.rag.answer import Answer, answer
from risklab.rag.index import SAMPLE_QUESTIONS
from risklab.rag.retrieve import retrieve

ROOT = Path(__file__).resolve().parents[1]
logger = logging.getLogger("eval_qa")

TECH = list(SAMPLE_PORTFOLIOS["Tech heavy"])
DEFENSIVE = list(SAMPLE_PORTFOLIOS["Defensive dividend"])

CASES: list[tuple[str, list[str]]] = [
    (SAMPLE_QUESTIONS[0], TECH),  # export controls
    (SAMPLE_QUESTIONS[2], TECH),  # competition from AI
    (SAMPLE_QUESTIONS[3], TECH),  # cybersecurity
    (SAMPLE_QUESTIONS[5], TECH),  # supply chain
    (SAMPLE_QUESTIONS[1], DEFENSIVE),  # interest rates
    (SAMPLE_QUESTIONS[4], DEFENSIVE),  # foreign currency
    (SAMPLE_QUESTIONS[6], DEFENSIVE),  # regulatory / antitrust
    (SAMPLE_QUESTIONS[7], DEFENSIVE),  # commodity / energy prices
    ("What does the company say about the weather on Mars?", TECH),  # off-topic control
]
"""Questions from ``rag.index.SAMPLE_QUESTIONS`` over two sample portfolios, plus an
off-topic control that should come back as insufficient evidence."""


def _git_commit() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def record(a: Answer, tickers: list[str], seconds: float) -> dict[str, Any]:
    """Per-question summary."""
    return {
        "question": a.query,
        "tickers": tickers,
        "retrieved": [c.chunk_id for c in a.chunks],
        "mode": a.mode,
        "attempts": a.attempts,
        "first_pass_ok": a.first_pass_ok,
        "insufficient_evidence": a.insufficient_evidence,
        "answer": a.answer,
        "claims": [{"text": c.text, "chunk_ids": list(c.chunk_ids)} for c in a.claims],
        "dropped_claims": [
            {"text": d.text, "chunk_ids": list(d.chunk_ids), "reasons": list(d.reasons)}
            for d in a.dropped_claims
        ],
        "citation_validity": a.citation_validity,
        "fallback_reason": a.fallback_reason,
        "seconds": round(seconds, 1),
    }


def summary(records: list[dict[str, Any]]) -> dict[str, Any]:
    """Aggregate counts."""
    n = len(records)
    cited = sum(len(r["claims"]) for r in records)
    return {
        "n_questions": n,
        "verified_first_pass": sum(bool(r["first_pass_ok"]) for r in records),
        "retried": sum(r["attempts"] > 1 for r in records),
        "llm_mode": sum(r["mode"] == "llm" for r in records),
        "retrieval_only": sum(r["mode"] == "retrieval_only" for r in records),
        "insufficient_evidence": sum(r["insufficient_evidence"] for r in records),
        "claims_kept": cited,
        "claims_dropped": sum(len(r["dropped_claims"]) for r in records),
        "citation_validity": 1.0
        if not cited
        else sum(r["citation_validity"] * len(r["claims"]) for r in records) / cited,
    }


def write_markdown(path: Path, result: dict[str, Any]) -> None:
    s = result["summary"]
    lines = [
        "# Q&A answer verification",
        "",
        f"Generated by `scripts/eval_qa.py` at {result['generated_at']} (commit "
        f"{result['git_commit']}). Provider **{result['provider']}**"
        + (f", model **{result['model']}**" if result["model"] else "")
        + ". Retrieval: hybrid, k=6, per-ticker quota 2, committed index.",
        "",
        "A claim is kept only if it cites retrieved chunk ids and every number in it appears "
        "in a passage it cites; a violation triggers one retry, then unsupported claims are "
        "dropped. If nothing survives, the page shows the passages only (retrieval-only).",
        "",
        f"- Questions: {s['n_questions']}; verified on first pass: {s['verified_first_pass']}; "
        f"retried: {s['retried']}",
        f"- Answered by the LLM: {s['llm_mode']}; retrieval-only: {s['retrieval_only']}; "
        f"flagged insufficient evidence: {s['insufficient_evidence']}",
        f"- Claims kept: {s['claims_kept']}; dropped: {s['claims_dropped']}; citation validity "
        f"of rendered claims: {100 * s['citation_validity']:.0f}%",
        "",
        "Faithfulness (does each kept claim say what its passage says?) is not machine-checked; "
        "the answers are listed below for a human spot check.",
        "",
    ]
    for i, r in enumerate(result["questions"], 1):
        lines += [
            f"## {i}. {r['question']}",
            "",
            f"Holdings: {', '.join(r['tickers'])}. Mode: **{r['mode']}**, attempts "
            f"{r['attempts']}, first pass {'ok' if r['first_pass_ok'] else 'failed'}"
            + (", insufficient evidence" if r["insufficient_evidence"] else "")
            + ".",
            "",
        ]
        if r["answer"]:
            lines += [f"> {r['answer']}", ""]
        for c in r["claims"]:
            lines.append(f"- {c['text']} `{', '.join(c['chunk_ids'])}`")
        for d in r["dropped_claims"]:
            lines.append(f"- ~~{d['text']}~~ dropped: {'; '.join(d['reasons'])}")
        if r["fallback_reason"]:
            lines.append(f"- Fallback: {r['fallback_reason']}")
        lines.append("")
    path.write_text("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument(
        "--provider", choices=["auto", "anthropic", "openai", "ollama", "none"], default=None
    )
    ap.add_argument("--out-dir", type=Path, default=ROOT / "docs" / "eval")
    args = ap.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    for noisy in ("chromadb", "httpx", "urllib3"):
        logging.getLogger(noisy).setLevel(logging.WARNING)
    settings = load_settings(llm_provider=args.provider) if args.provider else get_settings()
    status = resolve_provider(settings)
    llm = make_client(status, settings)
    logger.info("provider: %s (%s)", status.provider, status.reason)
    records = []
    for question, tickers in CASES:
        chunks = retrieve(question, tickers)
        t0 = time.perf_counter()
        a = answer(question, chunks, llm)
        rec = record(a, tickers, time.perf_counter() - t0)
        records.append(rec)
        logger.info(
            "%s -> %s, claims %d kept / %d dropped",
            question[:50],
            rec["mode"],
            len(rec["claims"]),
            len(rec["dropped_claims"]),
        )
    result = {
        "generated_at": datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC"),
        "git_commit": _git_commit(),
        "provider": status.provider,
        "model": status.model,
        "summary": summary(records),
        "questions": records,
    }
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "qa_verification.json").write_text(json.dumps(result, indent=1) + "\n")
    write_markdown(args.out_dir / "qa_verification.md", result)
    logger.info("summary: %s", json.dumps(result["summary"]))


if __name__ == "__main__":
    main()
